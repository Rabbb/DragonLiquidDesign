import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { spawnSync } from 'node:child_process'

const root = resolve(import.meta.dirname, '..')
const manifest = resolve(root, 'crates/dl-mdx-core/Cargo.toml')
const wasm = resolve(root, 'crates/dl-mdx-core/target/wasm32-unknown-unknown/release/dl_mdx_core.wasm')
const generated = resolve(root, 'packages/vue/src/components/dl-mdx-core.wasm.generated.ts')

const build = spawnSync('cargo', ['build', '--manifest-path', manifest, '--target', 'wasm32-unknown-unknown', '--release'], {
  cwd: root,
  encoding: 'utf8',
  stdio: 'inherit',
})
if (build.status !== 0) process.exit(build.status ?? 1)

const bytes = readFileSync(wasm)
const base64 = bytes.toString('base64')
const lines = base64.match(/.{1,100}/g) ?? []
const fingerprint = createHash('sha256').update(bytes).digest('hex')
const source = [
  '// Generated by scripts/build-mdx-rust.mjs. Do not edit by hand.',
  `export const dlMdxRustWasmSha256 = '${fingerprint}'`,
  `export const dlMdxRustWasmByteLength = ${bytes.byteLength}`,
  'export const dlMdxRustWasmBase64 = [',
  ...lines.map(line => `  '${line}',`),
  "].join('')",
  '',
].join('\n')

writeFileSync(generated, source, 'utf8')
console.log(`Generated Rust MarkdownX core: ${bytes.byteLength} bytes, sha256 ${fingerprint}`)
