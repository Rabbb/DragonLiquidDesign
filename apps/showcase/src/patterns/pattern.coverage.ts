export interface PatternScenarioCoverage {
  componentId: string
  scenarioId: string
  pageId: PatternPageId
}

export function scenarioCoverage(component: ComponentDefinition): PatternScenarioCoverage[] {
  const fallback = componentHomes[component.id]
  if (!fallback) return []
  return component.scenarios.map(scenario => ({
    componentId: component.id,
    scenarioId: scenario.id,
    pageId: scenarioPageOverrides[component.id]?.[scenario.id] ?? fallback,
  }))
}
