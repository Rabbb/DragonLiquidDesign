export function componentGuidanceFor(componentId: string): ComponentGuidance {
  const guidance = componentGuidance[componentId]
  if (!guidance) throw new Error(`组件 ${componentId} 缺少使用决策说明。`)
  return guidance
}

export function componentsMissingGuidance(componentIds: readonly string[]): string[] {
  return componentIds.filter(componentId => !componentGuidance[componentId])
}
