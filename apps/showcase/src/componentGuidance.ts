import inputControls from './input-controls.json' with { type: 'json' }

export type ComponentGuidance = {
  useWhen: readonly [string, string]
  avoidWhen: string
  accessibility: string
  example: string
}

function guide(
  useWhen: readonly [string, string],
  avoidWhen: string,
  accessibility: string,
  example: string,
): ComponentGuidance {
  return { useWhen, avoidWhen, accessibility, example }
}

